-- product_id に価格グループを含める形へ振り直す。
--
-- 商品URLは /products/<商品コード>/<価格グループ> という形をしており
-- (例: /products/E484457-000/01?colorDisplayCode=72)、この末尾の番号まで
-- 含めて初めて1つの値付けを指します。同じ商品が「現行の定価ライン」と
-- 「残り色・サイズの処分ライン」として同時に売られているためです。
--
-- 実測例(2026-08-19):
--   リブミニT E484457-000
--     /00 … ¥1,500 在庫28サイズ 値下げ表記なし        ← 定価ライン
--     /01 … ¥990  在庫6サイズ 「値下げ, 一部色サイズ対象」 ← 処分ライン
--   グラフィックT E483268-000        /00 ¥990  / /01 ¥790
--   ソフトシアークルーネックT E359527-000  /00 ¥790  / /01 ¥390
--
-- 従来の product_id は価格グループを落としていたため、この2本が1商品に潰れ、
-- 記録される価格が「その日の一覧ページがどちらのURLを載せたか」だけで往復して
-- いました。結果として同じ商品に price_up(値上げ)が毎日出続けます — 本物の
-- 値上げは一度きりのはずで、これが誤検知の証拠でした。
--
-- 既存行は url 列を持っているので、そこから product_id を計算し直せます。
-- 振り直さないと、旧IDの行が二度と更新されないままダッシュボードに residue
-- として残り続けます。
--
-- 色・サイズはクエリ文字列にあり product_id には含めません(同じ価格グループ内
-- では同一価格であり、まとめる前提で実行内の重複排除が組まれているため)。
--
-- このマイグレーションは冪等です。何度実行しても同じ結果になります。
update public.price_events as e
set product_id =
  e.brand
  || '-' || s.parts[1]
  || coalesce('-' || s.parts[2], '')
from (
  select
    id,
    regexp_match(url, '/products/([A-Za-z0-9-]+)(?:/([0-9]{1,3}))?') as parts
  from public.price_events
  where url ~ '/products/[A-Za-z0-9-]+'
) as s
where e.id = s.id
  and s.parts is not null
  -- 変化がない行は書き換えない(価格グループの無いURLや、実行済みの再適用)。
  and e.product_id is distinct from
      (e.brand || '-' || s.parts[1] || coalesce('-' || s.parts[2], ''));
